import 'dart:convert';

import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'api.dart';
import 'state.dart';

/// Social login panel: Facebook and TikTok (OAuth2 authorization code) and
/// Telegram (signed Login Widget payload).
///
/// SECURITY NOTE: the real identity data the providers return (real names,
/// profile pictures, e-mails) is stored ONLY in the backend `identity`
/// schema and is never surfaced in the Dating Profile or Anonymous Radar
/// features. Accounts created through a social login always carry a
/// pseudonymous display name (Nexus-XXXXXXXX) generated by the server.
class SocialLoginPanel extends ConsumerStatefulWidget {
  const SocialLoginPanel({super.key});

  @override
  ConsumerState<SocialLoginPanel> createState() => _SocialLoginPanelState();
}

class _SocialLoginPanelState extends ConsumerState<SocialLoginPanel> {
  String? _busy;
  String? _error;

  static const List<(String, String, IconData)> _providers = [
    ('facebook', 'Continue with Facebook', Icons.facebook),
    ('tiktok', 'Continue with TikTok', Icons.music_note),
    ('telegram', 'Continue with Telegram', Icons.send),
  ];

  void _toast(String message) {
    if (!mounted) return;
    ScaffoldMessenger.of(context)
        .showSnackBar(SnackBar(content: Text(message)));
  }

  Future<void> _start(String provider) async {
    setState(() {
      _busy = provider;
      _error = null;
    });
    try {
      if (provider == 'telegram') {
        // Telegram uses the signed Login Widget payload; there is no
        // OAuth2 authorize URL to fetch.
        if (!mounted) return;
        setState(() => _busy = null);
        if (!mounted) return;
        await _telegramSheet();
        return;
      }
      final start = await ref.read(apiProvider).startSocial(provider);
      if (!mounted) return;
      setState(() => _busy = null);
      if (!mounted) return;
      await _oauthSheet(provider, start);
    } on ApiError catch (e) {
      if (!mounted) return;
      setState(() {
        _busy = null;
        _error = e.message;
      });
    }
  }

  Future<void> _oauthSheet(String provider, SocialStart start) async {
    final codeCtrl = TextEditingController();
    String? sheetError;
    var submitting = false;
    await showModalBottomSheet<void>(
      context: context,
      isScrollControlled: true,
      shape: const RoundedRectangleBorder(
          borderRadius: BorderRadius.vertical(top: Radius.circular(24))),
      builder: (sheetCtx) => StatefulBuilder(
        builder: (sheetCtx, setSheet) => Padding(
          padding: EdgeInsets.fromLTRB(
              16, 16, 16, MediaQuery.of(sheetCtx).viewInsets.bottom + 16),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text('Sign in with ${provider[0].toUpperCase()}${provider.substring(1)}',
                  style: const TextStyle(
                      fontSize: 18, fontWeight: FontWeight.bold)),
              const SizedBox(height: 8),
              const Text(
                  '1. Open the authorization page in your browser and approve the request.'),
              SelectableText(start.authorizeUrl,
                  style: const TextStyle(fontSize: 12)),
              const SizedBox(height: 8),
              const Text('2. Paste the code from the redirect URL:'),
              TextField(
                key: const Key('social_code_field'),
                controller: codeCtrl,
                keyboardType: TextInputType.url,
                decoration: const InputDecoration(
                    labelText: 'Authorization code'),
              ),
              if (sheetError != null)
                Padding(
                  padding: const EdgeInsets.only(top: 8),
                  child: Text(sheetError!,
                      style: TextStyle(
                          color: Theme.of(sheetCtx).colorScheme.error)),
                ),
              const SizedBox(height: 12),
              FilledButton(
                onPressed: submitting
                    ? null
                    : () async {
                        setSheet(() => submitting = true);
                        try {
                          final res = await ref
                              .read(apiProvider)
                              .socialCallback(
                                  provider, codeCtrl.text.trim(), start.state);
                          if (!sheetCtx.mounted) return;
                          Navigator.of(sheetCtx).pop();
                          ref.read(authProvider).completeSocialLogin(res);
                          _toast('Signed in with $provider');
                        } on ApiError catch (e) {
                          setSheet(() {
                            submitting = false;
                            sheetError = e.message;
                          });
                        }
                      },
                child: submitting
                    ? const SizedBox(
                        width: 18,
                        height: 18,
                        child: CircularProgressIndicator(strokeWidth: 2))
                    : const Text('Complete sign-in'),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Future<void> _telegramSheet() async {
    final payloadCtrl = TextEditingController(text: '{\n'
        '  "id": "",\n'
        '  "first_name": "",\n'
        '  "auth_date": "",\n'
        '  "hash": ""\n'
        '}');
    String? sheetError;
    var submitting = false;
    await showModalBottomSheet<void>(
      context: context,
      isScrollControlled: true,
      shape: const RoundedRectangleBorder(
          borderRadius: BorderRadius.vertical(top: Radius.circular(24))),
      builder: (sheetCtx) => StatefulBuilder(
        builder: (sheetCtx, setSheet) => Padding(
          padding: EdgeInsets.fromLTRB(
              16, 16, 16, MediaQuery.of(sheetCtx).viewInsets.bottom + 16),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text('Sign in with Telegram',
                  style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
              const SizedBox(height: 8),
              const Text(
                  'Paste the Telegram Login Widget payload (JSON). The server '
                  'verifies the HMAC signature and freshness before signing in.'),
              const SizedBox(height: 8),
              TextField(
                key: const Key('social_payload_field'),
                controller: payloadCtrl,
                maxLines: 6,
                keyboardType: TextInputType.multiline,
              ),
              if (sheetError != null)
                Padding(
                  padding: const EdgeInsets.only(top: 8),
                  child: Text(sheetError!,
                      style: TextStyle(
                          color: Theme.of(sheetCtx).colorScheme.error)),
                ),
              const SizedBox(height: 12),
              FilledButton(
                onPressed: submitting
                    ? null
                    : () async {
                        Map<String, String> payload;
                        try {
                          final decoded = jsonDecode(payloadCtrl.text.trim());
                          if (decoded is! Map<String, dynamic>) {
                            throw const FormatException('expected a JSON object');
                          }
                          payload = decoded
                              .map((k, v) => MapEntry(k, v.toString()));
                        } on FormatException catch (_) {
                          setSheet(() => sheetError = 'Payload must be a JSON object');
                          return;
                        }
                        setSheet(() => submitting = true);
                        try {
                          final res =
                              await ref.read(apiProvider).telegramLogin(payload);
                          if (!sheetCtx.mounted) return;
                          Navigator.of(sheetCtx).pop();
                          ref.read(authProvider).completeSocialLogin(res);
                          _toast('Signed in with telegram');
                        } on ApiError catch (e) {
                          setSheet(() {
                            submitting = false;
                            sheetError = e.message;
                          });
                        }
                      },
                child: submitting
                    ? const SizedBox(
                        width: 18,
                        height: 18,
                        child: CircularProgressIndicator(strokeWidth: 2))
                    : const Text('Complete sign-in'),
              ),
            ],
          ),
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Card(
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Chip(
              label: Text('SOCIAL LOGINS'),
              avatar: Icon(Icons.verified_user, size: 16),
            ),
            const SizedBox(height: 4),
            const Text(
              'Provider identity data (real names, photos) is kept isolated '
              'from your Dating Profile and Anonymous Radar presence.',
              style: TextStyle(fontSize: 12),
            ),
            const SizedBox(height: 12),
            for (final (provider, label, icon) in _providers) ...[
              OutlinedButton.icon(
                key: Key('social_$provider'),
                onPressed: _busy == null ? () => _start(provider) : null,
                icon: _busy == provider
                    ? const SizedBox(
                        width: 16,
                        height: 16,
                        child: CircularProgressIndicator(strokeWidth: 2))
                    : Icon(icon, size: 20),
                label: Text(label),
              ),
              const SizedBox(height: 8),
            ],
            if (_error != null)
              Text(_error!,
                  style: TextStyle(color: Theme.of(context).colorScheme.error)),
          ],
        ),
      ),
    );
  }
}
